"""Generate boards.json (leaderboard sort order + names) from the game's own track list.

Reads pack0/tracks.xml out of build/data/data.pak and classifies every leaderboard:
  - skill games scored in points (p_* medal limits)  -> higher is better
  - Trials HD skill games (ultimate limit above silver, e.g. Ski Jump)  -> higher is better
  - a <skillgameconfig> <score sorting="..."> overrides both (desc = higher is better)
  - everything else (races, time-only skill games)  -> fewest faults, then lowest time

When the converted Xbox 360 DLC packs exist (O:/trialsevo/dlc_pc, see dlc_leaderboards.py), their
pack<N>/tracks.xml (with the renumbered PC leaderboard ids) are classified the same way.

Usage:  python tools/gen_boards.py ["C:/.../TrialsPC/build/data/data.pak"] [<dlc_pc root>]
"""
import json
import os
import re
import struct
import sys
import zlib

DEFAULT_PAK = r"C:\Program Files (x86)\Steam\steamapps\common\TrialsPC\build\data\data.pak"
DEFAULT_DLC_ROOT = r"O:\trialsevo\dlc_pc"
OUT = os.path.join(os.path.dirname(__file__), "..", "boards.json")


def read_pak_file(pak_path, wanted):
    """data.pak: u32 magic 0x12345678, u32 data_start, u32 count, then count x 17-byte entries
    (u32 hash, u32 packed_size, u32 size, u8 method (8 = deflate), u32 offset); file names are a
    table of (u16 len, name) in entry order after the data."""
    d = open(pak_path, "rb").read()
    magic, _data_start, count = struct.unpack_from("<III", d, 0)
    if magic != 0x12345678:
        raise ValueError("not a Trials pak file")
    entries = [struct.unpack_from("<IIIBI", d, 12 + i * 17) for i in range(count)]
    # The name table starts at the first entry name; find it from a name every pack has.
    o = d.rfind(b"\x00areavolumes.xml") - 1
    names = []
    while len(names) < count:
        n = struct.unpack_from("<H", d, o)[0]
        names.append(d[o + 2:o + 2 + n].decode("latin-1"))
        o += 2 + n
    for name, (_h, packed, size, method, offset) in zip(names, entries):
        if name == wanted:
            raw = d[offset:offset + packed]
            return zlib.decompress(raw) if method == 8 else raw
    raise KeyError(wanted)


def _limit(text):
    """Medal limit as a comparable tuple: "1:44:000" -> (1, 44, 0), "64" -> (64,)."""
    return tuple(int(p) for p in text.split(":")) if text else ()


def classify(xml, boards, higher, pack=0):
    for m in re.finditer(r"(<!--([^-]*?)-->\s*)?<Track\b([^>]*)>(.*?)</Track>", xml, re.S):
        attrs = dict(re.findall(r'(\w+)="([^"]*)"', m.group(3)))
        board = int(attrs.get("leaderboard_id", "0") or 0)
        if not board or (pack and int(attrs["id"]) >= 65000):   # DLC per-pack placeholder tracks
            continue
        limits = re.search(r"<Limits\b([^>]*)>", m.group(4))
        keys = re.findall(r'(\w+)="', limits.group(1)) if limits else []
        values = dict(re.findall(r'(\w+)="([^"]*)"', limits.group(1))) if limits else {}
        points = (any(k.startswith("p_") for k in keys)
                  or _limit(values.get("ultimate")) > _limit(values.get("silver")))
        score = re.search(r'<score\b[^>]*\bsorting="(\w+)"', m.group(4))
        if score:                # skillgameconfig names the order (Adrenaline Cannon: asc distance)
            points = score.group(1) == "desc"
        name = (m.group(2) or "").strip()
        if "<" in name:          # a commented-out <Track> block, not a title comment
            name = ""
        boards[board] = {"track": int(attrs["id"]), "mode": attrs.get("mode"),
                         "name": name, "higher_is_better": points}
        if pack:
            boards[board]["dlc_pack"] = pack
        if points:
            higher.append(board)


def main():
    pak = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_PAK
    dlc_root = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_DLC_ROOT
    boards, higher = {}, []
    classify(read_pak_file(pak, "pack0/tracks.xml").decode("utf-8", "replace"), boards, higher)
    if os.path.isdir(dlc_root):
        from dlc_leaderboards import PACKS, load_tracks      # imports this module: load lazily
        for folder, pack in PACKS:
            path = os.path.join(dlc_root, folder, "data", "configs.pak")
            if os.path.exists(path):
                xml = load_tracks(path, pack)[3].decode("utf-8", "replace")
                before = len(boards)
                classify(xml, boards, higher, pack)
                print(f"pack{pack} ({folder}): {len(boards) - before} leaderboards")
    data = {"_comment": "Generated by tools/gen_boards.py from the game's pack0/tracks.xml (+ DLC pack<N>/tracks.xml).",
            "higher_is_better": sorted(set(higher)),
            "boards": {str(k): v for k, v in sorted(boards.items())}}
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1)
    print(f"{len(boards)} leaderboards, {len(higher)} ranked higher-is-better -> {os.path.abspath(OUT)}")


if __name__ == "__main__":
    main()
